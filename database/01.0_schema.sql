# 01_schema.sql — Creación de la estructura de la base de datos

```sql
/*
============================================================
ARCHIVO: 01_schema.sql

FUNCIÓN:
Crear la estructura relacional de la base de datos:
tablas, columnas, claves, restricciones, relaciones e índices.

IMPORTANCIA:
Implementa el modelo relacional diseñado previamente en:
- docs/02_entities-and-attributes.md
- docs/03_diagram-er.md
- docs/04_relation-model.dbml
- docs/05_normalization.md

ORDEN DE EJECUCIÓN:
1. Crear la base de datos con 00_create_db.sql.
2. Conectarse a ella.
3. Ejecutar este archivo.
4. Insertar datos con 02_seed.sql.

IMPORTANTE:
Ejecutar después de conectarse a la base de datos correcta.
============================================================
*/

/*
------------------------------------------------------------
1. CONFIGURACIÓN INICIAL
------------------------------------------------------------

SET search_path:
Establece el esquema utilizado para las operaciones SQL.

Un esquema organiza objetos como tablas, vistas y funciones.
En PostgreSQL, public es el esquema predeterminado.
*/
SET search_path TO public;

/*
------------------------------------------------------------
2. CREACIÓN DE TABLAS
------------------------------------------------------------

CREATE TABLE:
Crea una tabla formada por columnas y registros.

- Columna: representa un atributo de una entidad.
- Registro: representa una instancia de esa entidad.

SINTAXIS:
CREATE TABLE nombre_tabla (
    columna tipo_dato restricciones
);

IMPORTANTE:
Crear primero las tablas de las que dependen otras.
Las tablas referenciadas mediante FOREIGN KEY deben existir,
salvo que la relación se agregue posteriormente con ALTER TABLE.
*/

/*
------------------------------------------------------------
3. TIPOS DE DATOS
------------------------------------------------------------

NUMÉRICOS:
- SMALLINT: entero pequeño.
- INTEGER: entero.
- BIGINT: entero de mayor capacidad.
- NUMERIC(precision, scale): decimal de precisión definida.

TEXTO:
- CHAR(n): longitud fija.
- VARCHAR(n): longitud variable con límite.
- TEXT: longitud variable sin límite declarado.

LÓGICO:
- BOOLEAN: TRUE, FALSE o NULL.

FECHA Y TIEMPO:
- DATE: fecha.
- TIME: hora.
- TIMESTAMP: fecha y hora sin zona horaria.
- TIMESTAMPTZ: instante temporal con manejo de zona horaria.

IMPORTANTE:
Elegir el tipo según el significado del atributo
y las operaciones que se realizarán con él.
*/

/*
------------------------------------------------------------
4. IDENTIFICADORES AUTOMÁTICOS
------------------------------------------------------------

SERIAL:
Mecanismo heredado de PostgreSQL que utiliza una secuencia
para generar identificadores enteros.

IDENTITY:
Alternativa moderna y estándar de SQL.

GENERATED ALWAYS AS IDENTITY:
Genera valores automáticamente y restringe la asignación
manual de valores, salvo mecanismos específicos.

GENERATED BY DEFAULT AS IDENTITY:
Genera valores automáticamente, pero permite proporcionar
valores explícitos.

EJEMPLOS:
id SERIAL PRIMARY KEY

id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY
*/

/*
------------------------------------------------------------
5. CLAVES PRIMARIAS (PRIMARY KEY)
------------------------------------------------------------

Identifican de manera única cada registro.

CARACTERÍSTICAS:
- No admiten valores duplicados.
- No admiten NULL.
- Una tabla tiene una sola restricción PRIMARY KEY.
- Pueden estar formadas por una o varias columnas.

EJEMPLO:
id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY

CLAVE COMPUESTA:
PRIMARY KEY (student_id, course_id)
*/

/*
------------------------------------------------------------
6. CLAVES FORÁNEAS (FOREIGN KEY)
------------------------------------------------------------

Establecen relaciones entre columnas de diferentes tablas,
normalmente apuntando a una PRIMARY KEY.

EJEMPLOS:
student_id INTEGER REFERENCES students(id)

FOREIGN KEY (student_id) REFERENCES students(id)

FUNCIÓN:
Garantizar la integridad referencial y evitar referencias
a registros inexistentes, salvo que la relación permita NULL.

IMPORTANTE:
La tabla referenciada debe existir al crear la restricción.
*/

/*
------------------------------------------------------------
7. RESTRICCIONES (CONSTRAINTS)
------------------------------------------------------------

Establecen condiciones que deben cumplir los datos.

- NOT NULL: impide almacenar NULL.
- UNIQUE: evita valores o combinaciones duplicadas.
- CHECK: exige que se cumpla una expresión lógica.
- DEFAULT: asigna un valor si no se proporciona uno.
- PRIMARY KEY: define la clave primaria.
- FOREIGN KEY: define una clave foránea.

EJEMPLOS:
email VARCHAR(150) NOT NULL UNIQUE
age INTEGER CHECK (age >= 0)
status VARCHAR(20) DEFAULT 'active'

IMPORTANTE:
CHECK no sustituye las validaciones necesarias
en la aplicación.
*/

/*
------------------------------------------------------------
8. EJEMPLO DE CREACIÓN DE TABLAS
------------------------------------------------------------

Ejemplo académico: students, courses y enrollments.

ORDEN:
1. students
2. courses
3. enrollments

La tabla enrollments depende de las otras dos.
*/

CREATE TABLE students (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE courses (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE enrollments (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    course_id INTEGER NOT NULL,
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_enrollments_student
        FOREIGN KEY (student_id) REFERENCES students(id),
    CONSTRAINT fk_enrollments_course
        FOREIGN KEY (course_id) REFERENCES courses(id),
    CONSTRAINT uq_enrollments_student_course
        UNIQUE (student_id, course_id)
);

/*
------------------------------------------------------------
9. ACCIONES DE LAS CLAVES FORÁNEAS
------------------------------------------------------------

ON DELETE:
Define qué sucede al eliminar el registro referenciado.

ON UPDATE:
Define qué sucede al modificar la clave referenciada.

ACCIONES:
- CASCADE: propaga la operación a registros relacionados.
- RESTRICT: impide la operación si existen dependencias.
- NO ACTION: impide violar la integridad referencial
  cuando se comprueba la restricción.
- SET NULL: establece NULL en la clave foránea.
- SET DEFAULT: establece su valor predeterminado.

IMPORTANTE:
Elegir según las reglas del negocio. No usar CASCADE
sin analizar las consecuencias de eliminar datos.
*/

/*
------------------------------------------------------------
10. ALTER TABLE
------------------------------------------------------------

Permite modificar la estructura de una tabla existente.

OPERACIONES:
- ADD COLUMN: agregar columna.
- ALTER COLUMN: modificar propiedades.
- DROP COLUMN: eliminar columna.
- ADD CONSTRAINT: agregar restricción.
- DROP CONSTRAINT: eliminar restricción.

EJEMPLOS:
ALTER TABLE students ADD COLUMN phone VARCHAR(20);

ALTER TABLE students
ADD CONSTRAINT uq_students_phone UNIQUE (phone);

IMPORTANTE:
Documentar los cambios. En proyectos con migraciones,
registrarlos mediante archivos de migración.
*/

/*
------------------------------------------------------------
11. ÍNDICES (CREATE INDEX)
------------------------------------------------------------

Crean estructuras auxiliares que pueden mejorar
el rendimiento de determinadas consultas.

EJEMPLOS:
CREATE INDEX idx_students_last_name
ON students(last_name);

CREATE UNIQUE INDEX idx_students_email
ON students(email);

IMPORTANTE:
PRIMARY KEY y UNIQUE normalmente crean sus propios índices.
Evitar duplicados sin justificación.

Los índices consumen almacenamiento y agregan trabajo
a las operaciones de escritura.
*/

/*
------------------------------------------------------------
12. COMENTARIOS SOBRE OBJETOS
------------------------------------------------------------

COMMENT ON:
Permite documentar objetos de PostgreSQL, como bases
de datos, tablas, columnas, esquemas e índices.

EJEMPLOS:
COMMENT ON TABLE students
IS 'Almacena la información de los estudiantes';

COMMENT ON COLUMN students.email
IS 'Correo electrónico único del estudiante';

Los comentarios se almacenan como metadatos en PostgreSQL.
*/

/*
------------------------------------------------------------
13. VALIDACIÓN DE LA ESTRUCTURA
------------------------------------------------------------

Después de ejecutar el archivo, comprobar las tablas
y columnas creadas.

LISTAR TABLAS:
*/
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;

/*
REVISAR COLUMNAS:
*/
SELECT
    table_name,
    column_name,
    data_type,
    is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
ORDER BY table_name, ordinal_position;

/*
============================================================
RESULTADO ESPERADO:
- Tablas y columnas creadas.
- Tipos de datos apropiados.
- Claves primarias y foráneas definidas.
- Restricciones que protegen la integridad.
- Índices justificados.
- Estructura coincidente con el modelo relacional.

SIGUIENTE ARCHIVO:
02_seed.sql

Aquí insertaremos datos iniciales y registros de prueba
para verificar el funcionamiento de la estructura.
============================================================
*/
```
