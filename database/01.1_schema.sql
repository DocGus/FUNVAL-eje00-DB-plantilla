CREATE TABLE enrollments (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    course_id INTEGER NOT NULL,
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_enrollments_student
        FOREIGN KEY (student_id)
        REFERENCES students(id),

    CONSTRAINT fk_enrollments_course
        FOREIGN KEY (course_id)
        REFERENCES courses(id),

    CONSTRAINT uq_enrollments_student_course
        UNIQUE (student_id, course_id)
);
*/


/*
------------------------------------------------------------
9. ACCIONES DE LAS CLAVES FORÁNEAS
------------------------------------------------------------

ON DELETE:
Define qué sucede cuando se elimina el registro referenciado.

ON UPDATE:
Define qué sucede cuando se modifica la clave referenciada.

ACCIONES DISPONIBLES:

CASCADE:
Propaga la operación a los registros relacionados.

RESTRICT:
Impide la operación cuando existen registros dependientes.

NO ACTION:
Impide que se viole la integridad referencial
cuando se comprueba la restricción.

SET NULL:
Establece NULL en la clave foránea relacionada.

SET DEFAULT:
Establece el valor predeterminado de la clave foránea.

IMPORTANTE:
La acción debe corresponder a las reglas del negocio.

No debemos utilizar ON DELETE CASCADE sin analizar
las consecuencias de eliminar registros relacionados.
*/


/*
------------------------------------------------------------
10. ALTER TABLE
------------------------------------------------------------

ALTER TABLE:
Permite modificar la estructura de una tabla existente.

OPERACIONES COMUNES:

ADD COLUMN:
Agregar una columna.

ALTER COLUMN:
Modificar las propiedades de una columna.

DROP COLUMN:
Eliminar una columna.

ADD CONSTRAINT:
Agregar una restricción.

DROP CONSTRAINT:
Eliminar una restricción.

EJEMPLOS:

ALTER TABLE students
ADD COLUMN phone VARCHAR(20);

ALTER TABLE students
ADD CONSTRAINT uq_students_phone UNIQUE (phone);

IMPORTANTE:
Los cambios estructurales realizados después de la creación
inicial deben controlarse y documentarse.
En proyectos con migraciones, estos cambios normalmente
se registran mediante archivos de migración.
*/


/*
------------------------------------------------------------
11. ÍNDICES (CREATE INDEX)
------------------------------------------------------------

CREATE INDEX:
Crea una estructura auxiliar que puede mejorar
el rendimiento de determinadas consultas.

EJEMPLO:

CREATE INDEX idx_students_last_name
ON students(last_name);

ÍNDICE ÚNICO:

CREATE UNIQUE INDEX idx_students_email
ON students(email);

IMPORTANTE:
Las restricciones PRIMARY KEY y UNIQUE normalmente
crean sus propios índices en PostgreSQL.

No debemos crear índices duplicados sin justificación.

Los índices mejoran ciertas lecturas, pero también
consumen almacenamiento y agregan trabajo a las escrituras.
*/


/*
------------------------------------------------------------
12. COMENTARIOS SOBRE OBJETOS
------------------------------------------------------------

COMMENT ON:
Permite documentar objetos de PostgreSQL.

Podemos agregar comentarios a:

- DATABASE
- TABLE
- COLUMN
- SCHEMA
- INDEX
- Y otros objetos compatibles.

EJEMPLO:

COMMENT ON TABLE students
IS 'Almacena la información de los estudiantes';

COMMENT ON COLUMN students.email
IS 'Correo electrónico único del estudiante';

IMPORTANTE:
Estos comentarios se almacenan como metadatos
en PostgreSQL y pueden consultarse desde herramientas
de administración.
*/


