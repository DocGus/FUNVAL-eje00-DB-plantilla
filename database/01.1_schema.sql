/*
------------------------------------------------------------
2. CREACIÓN DE TABLAS
------------------------------------------------------------

CREATE TABLE:
Instrucción SQL que crea una tabla dentro de la base
de datos seleccionada.

Una tabla está formada por columnas y registros.

Cada columna representa un atributo de la entidad.
Cada registro representa una instancia de esa entidad.

SINTAXIS GENERAL:

CREATE TABLE nombre_tabla (
    columna tipo_dato restricciones,
    columna tipo_dato restricciones
);

IMPORTANTE:
Antes de crear las tablas debemos identificar sus dependencias.

Las tablas referenciadas mediante FOREIGN KEY deben existir
antes de crear la tabla que las referencia, salvo que
agreguemos posteriormente la restricción mediante ALTER TABLE.
*/


/*
------------------------------------------------------------
3. TIPOS DE DATOS
------------------------------------------------------------

Los tipos de datos determinan qué clase de información
puede almacenarse en cada columna.

TIPOS NUMÉRICOS:

SMALLINT:
Entero pequeño.

INTEGER:
Número entero.

BIGINT:
Número entero de mayor capacidad.

NUMERIC(precision, scale):
Número decimal de precisión definida.
Útil para importes y cantidades que requieren exactitud.

TIPOS DE TEXTO:

CHAR(n):
Texto de longitud fija.

VARCHAR(n):
Texto de longitud variable con límite de caracteres.

TEXT:
Texto de longitud variable sin límite declarado.

TIPOS LÓGICOS:

BOOLEAN:
Acepta TRUE, FALSE o NULL.

TIPOS DE FECHA Y TIEMPO:

DATE:
Almacena una fecha.

TIME:
Almacena una hora.

TIMESTAMP:
Almacena fecha y hora sin zona horaria.

TIMESTAMPTZ:
Almacena un instante temporal con manejo de zona horaria.

IMPORTANTE:
La selección del tipo debe responder al significado
del atributo y a las operaciones que realizaremos con él.
*/


/*
------------------------------------------------------------
4. IDENTIFICADORES AUTOMÁTICOS
------------------------------------------------------------

SERIAL:
Mecanismo heredado de PostgreSQL que utiliza una secuencia
para generar valores enteros automáticamente.

Ejemplo:

id SERIAL PRIMARY KEY

GENERATED ALWAYS AS IDENTITY:
Mecanismo estándar de SQL para generar valores
automáticamente mediante una columna de identidad.

Ejemplo:

id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY

GENERATED BY DEFAULT AS IDENTITY:
Permite generar valores automáticamente, pero también
acepta valores proporcionados explícitamente.

RECOMENDACIÓN:
Para nuevos proyectos PostgreSQL podemos utilizar
IDENTITY como alternativa moderna a SERIAL.
*/


/*
------------------------------------------------------------
5. CLAVES PRIMARIAS (PRIMARY KEY)
------------------------------------------------------------

PRIMARY KEY:
Identifica de manera única cada registro de una tabla.

CARACTERÍSTICAS:

- No admite valores duplicados.
- No admite valores NULL.
- Una tabla tiene una sola restricción PRIMARY KEY.
- Puede estar formada por una o varias columnas.

EJEMPLO:

id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY

CLAVE PRIMARIA COMPUESTA:

PRIMARY KEY (student_id, course_id)

Se utiliza cuando la identificación de un registro
depende de la combinación de varias columnas.
*/


/*
------------------------------------------------------------
6. CLAVES FORÁNEAS (FOREIGN KEY)
------------------------------------------------------------

FOREIGN KEY:
Establece una relación entre una columna o conjunto
de columnas de una tabla y una clave candidata
de otra tabla, normalmente su PRIMARY KEY.

EJEMPLO:

student_id INTEGER REFERENCES students(id)

También puede declararse al final de la tabla:

FOREIGN KEY (student_id) REFERENCES students(id)

FUNCIÓN:
Garantizar la integridad referencial.

Esto significa que no podremos registrar una referencia
a un estudiante que no exista, salvo que la relación
permita NULL.

IMPORTANTE:
La tabla referenciada debe existir cuando se crea
la restricción FOREIGN KEY.
*/


/*
------------------------------------------------------------
7. RESTRICCIONES (CONSTRAINTS)
------------------------------------------------------------

Las restricciones establecen condiciones que deben
cumplir los datos almacenados.

NOT NULL:
Impide almacenar NULL en una columna.

UNIQUE:
Impide que se repita un valor o una combinación
de valores dentro de la tabla.

CHECK:
Exige que una expresión lógica se cumpla para cada
registro insertado o actualizado.

DEFAULT:
Asigna un valor cuando no se proporciona uno
en la operación INSERT.

PRIMARY KEY:
Define la clave primaria.

FOREIGN KEY:
Define una clave foránea.

EJEMPLOS:

email VARCHAR(150) NOT NULL UNIQUE

age INTEGER CHECK (age >= 0)

status VARCHAR(20) DEFAULT 'active'

IMPORTANTE:
Una restricción CHECK no sustituye las reglas de validación
que deban implementarse en la aplicación.
*/


